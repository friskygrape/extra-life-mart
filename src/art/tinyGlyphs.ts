/** Width in game pixels of text in the small font, with one pixel between letters and a narrow word space. */
export function tinyTextWidth(text: string): number {
  return [...text].reduce((sum, ch) => sum + tinyAdvance(ch), 0) - 1;
}

export function tinyAdvance(ch: string): number {
  return ch === ' ' ? 2 : TINY_GLYPHS[ch].split('|')[0].length + 1;
}
